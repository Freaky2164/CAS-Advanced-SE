-- Änderungshistorie mit Hibernate Envers (ersetzt die Feldhistorie aus
-- CDisplayFieldHistoryBean / CHistoryDialog des Altsystems).
-- Auditiert werden bewusst nur fachlich relevante Stammdaten; reine Lookup-Listen
-- wie Anrede oder Spendentyp bleiben ohne Historie.

CREATE TABLE app.revinfo (
    rev       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp  bigint      NOT NULL,
    username  varchar(50)
);

CREATE TABLE frauenhaus.mitglied_aud (
    mitglied      bigint        NOT NULL,
    rev           bigint        NOT NULL REFERENCES app.revinfo (rev),
    revtype       smallint,
    anrede        varchar(50),
    vorname       varchar(100),
    name          varchar(100)  NOT NULL,
    name2         varchar(100),
    name3         varchar(100),
    briefanrede   varchar(200),
    strasse       varchar(200),
    plz           varchar(10),
    ort           varchar(100),
    email         varchar(200),
    tel1          varchar(50),
    tel2          varchar(50),
    fax           varchar(50),
    foerderverein boolean       NOT NULL,
    frauenhaus    boolean       NOT NULL,
    bemerkung     text,
    PRIMARY KEY (mitglied, rev)
);

CREATE TABLE frauenhaus.verein_aud (
    verein       varchar(50)  NOT NULL,
    rev          bigint       NOT NULL REFERENCES app.revinfo (rev),
    revtype      smallint,
    bezeichnung  varchar(200) NOT NULL,
    PRIMARY KEY (verein, rev)
);

CREATE TABLE frauenhaus.gericht_aud (
    gericht      bigint       NOT NULL,
    rev          bigint       NOT NULL REFERENCES app.revinfo (rev),
    revtype      smallint,
    bezeichnung  varchar(200) NOT NULL,
    strasse      varchar(200),
    plz          varchar(10),
    ort          varchar(100),
    PRIMARY KEY (gericht, rev)
);

CREATE TABLE frauenhaus.spende_aud (
    spende       bigint        NOT NULL,
    rev          bigint        NOT NULL REFERENCES app.revinfo (rev),
    revtype      smallint,
    mitglied     bigint        NOT NULL,
    spendenart   varchar(100)  NOT NULL,
    verein       varchar(50)   NOT NULL,
    datum        date          NOT NULL,
    betrag       numeric(12,2) NOT NULL,
    bemerkung    text,
    PRIMARY KEY (spende, rev)
);

CREATE TABLE frauenhaus.bussgeld_aud (
    bussgeld     bigint        NOT NULL,
    rev          bigint        NOT NULL REFERENCES app.revinfo (rev),
    revtype      smallint,
    gericht      bigint        NOT NULL,
    verein       varchar(50)   NOT NULL,
    status       varchar(50),
    name         varchar(100),
    vorname      varchar(100),
    aktenzeichen varchar(100),
    datum        date          NOT NULL,
    zieldatum    date,
    betrag       numeric(12,2) NOT NULL,
    bezahlt      boolean       NOT NULL,
    bemerkung    text,
    PRIMARY KEY (bussgeld, rev)
);
